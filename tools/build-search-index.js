#!/usr/bin/env node
/* Builds js/data/search-index.js: the text of every lesson section, lab guide and cheat-sheet section, for the site-wide search.
 * Glossary terms, FAQ entries, labs, module summaries and operating-system profiles are searched straight from their data files,
 * so only page text needs indexing.
 *
 *   node tools/build-search-index.js          write the file
 *   node tools/build-search-index.js --check  exit 1 if the committed file is out of date (the tests run this)
 *
 * Each section is [url, page title, heading, text, kind]. The url ends in #id, where the id is the heading's own id or one that
 * js/site.js gives it at run time with the same rule (headingIds below and in site.js must match). */
"use strict";
const fs = require("node:fs"), path = require("node:path");
const { JSDOM } = require("jsdom");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "js", "data", "search-index.js");
const MAX_TEXT = 2500;

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "section";
const clean = (s) => s.replace(/\s+/g, " ").trim();

/** The id each <h2> without one receives: its slug, made unique among all ids already on the page. Same rule as js/site.js. */
function headingIds(doc) {
  const used = new Set([...doc.querySelectorAll("[id]")].map((e) => e.id));
  const ids = new Map();
  doc.querySelectorAll("main h2").forEach((h) => {
    if (h.id) { ids.set(h, h.id); return; }
    const base = slug(h.textContent);
    let id = base, n = 2;
    while (used.has(id)) id = `${base}-${n++}`;
    used.add(id); ids.set(h, id);
  });
  return ids;
}

/** Text of an element for searching: no code listings, tables of contents, simulations or quizzes (those are not prose). */
function proseOf(el) {
  const copy = el.cloneNode(true);
  if (copy.matches && copy.matches("pre, .toc, [data-sim], [data-quiz], .pager, script, style")) return "";
  copy.querySelectorAll("pre, .toc, [data-sim], [data-quiz], .pager, script, style").forEach((n) => n.remove());
  copy.querySelectorAll(".code-tabs").forEach((n) => { n.replaceWith(...[...n.querySelectorAll(".lang-note")]); });
  return clean(copy.textContent);
}

function pages() {
  const out = [];
  const mods = fs.readdirSync(path.join(ROOT, "modules")).filter((f) => /^\d\d-.*\.html$/.test(f)).sort();
  mods.forEach((f) => out.push({ file: `modules/${f}`, kind: "Lesson" }));
  out.push({ file: "cheatsheet.html", kind: "Cheat sheet" });
  fs.readdirSync(path.join(ROOT, "labs")).filter((f) => /^\d\d-.*\.html$/.test(f)).sort().forEach((f) => out.push({ file: `labs/${f}`, kind: "Lab" }));
  return out;
}

function buildSections() {
  const sections = [];
  for (const p of pages()) {
    const doc = new JSDOM(fs.readFileSync(path.join(ROOT, p.file), "utf8")).window.document;
    const main = doc.querySelector("main");
    if (!main) continue;
    const ids = headingIds(doc);
    const h1 = main.querySelector("h1");
    const eyebrow = (main.querySelector(".eyebrow") || {}).textContent;
    const pageTitle = clean(p.kind === "Lesson" && eyebrow && h1 ? `${eyebrow.split("·")[0].trim()}: ${h1.textContent}` : (h1 ? h1.textContent : doc.title));
    let heading = h1 ? clean(h1.textContent) : pageTitle, id = "", text = "";
    const flush = () => { const t = clean(text); if (t) sections.push([id ? `${p.file}#${id}` : p.file, pageTitle, heading, t.slice(0, MAX_TEXT), p.kind]); text = ""; };
    for (const child of main.children) {
      if (child.tagName === "H1") continue;
      if (child.tagName === "H2") { flush(); heading = clean(child.textContent); id = ids.get(child); continue; }
      if (child.matches(".eyebrow")) continue;
      text += " " + proseOf(child);
    }
    flush();
  }
  return sections;
}

function render(sections) {
  return `/* GENERATED by tools/build-search-index.js: do not edit by hand (run \`npm run build:search\`).
   Page text for the site-wide search: [url, page title, section heading, text, kind]. */
window.OSData = window.OSData || {};
window.OSData.searchIndex = [
${sections.map((s) => "  " + JSON.stringify(s)).join(",\n")}
];
`;
}

module.exports = { buildSections, render, headingIds, slug, OUT };

if (require.main === module) {
  const out = render(buildSections());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== out) { console.error("js/data/search-index.js is out of date. Run: npm run build:search"); process.exit(1); }
    console.log("search index is up to date");
  } else {
    fs.writeFileSync(OUT, out);
    console.log(`Wrote ${path.relative(ROOT, OUT)}: ${out.split("\n").length - 6} sections, ${(out.length / 1024).toFixed(0)} KB.`);
  }
}
