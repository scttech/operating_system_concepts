#!/usr/bin/env node
/* Builds js/data/glossary-index.js: for every glossary term, where it is discussed in the modules.
 *
 *   node tools/build-glossary-index.js          write the file
 *   node tools/build-glossary-index.js --check  exit 1 if the committed file is out of date (used by the tests)
 *
 * "dfn"     = the module marks the term with <dfn data-term="…"> (a definition / first discussion)
 * "mention" = the term appears in the module text at least MIN_MENTIONS times without being marked
 */
"use strict";
const fs = require("node:fs"), path = require("node:path");
const { JSDOM } = require("jsdom");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "js", "data", "glossary-index.js");
const MIN_MENTIONS = 2;

// Same rule as OSSite.slug in js/site.js (anchors must match what the browser assigns at run time).
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

function loadData() {
  const saved = globalThis.window;
  globalThis.window = globalThis;
  delete globalThis.OSData;
  for (const f of ["modules", "glossary"]) {
    const p = path.join(ROOT, "js", "data", `${f}.js`);
    delete require.cache[require.resolve(p)];
    require(p);
  }
  const data = globalThis.OSData;
  if (saved === undefined) delete globalThis.window; else globalThis.window = saved;
  return data;
}

/** "Access control list (ACL)" -> ["Access control list", "ACL"]; plain terms -> [term]. */
function aliases(term) {
  const m = /^(.*?)\s*\(([^)]+)\)\s*$/.exec(term);
  return m ? [m[1], m[2]] : [term];
}
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
function countMentions(text, term) {
  let n = 0;
  for (const a of aliases(term)) {
    const abbreviation = /^[A-Z0-9/.-]{2,}$/.test(a);   // ACL, TLB, DMA: match case-sensitively
    if (!abbreviation && a.length < 5) continue;       // "Page", "Block", "Heap" are too common to count as mentions
    const re = new RegExp(`(^|[^\\w])${escapeRe(a)}(?=$|[^\\w])`, abbreviation ? "g" : "gi");
    n += (text.match(re) || []).length;
  }
  return n;
}

function buildIndex() {
  const data = loadData();
  const byLower = new Map(data.glossary.map((g) => [g.term.toLowerCase(), g.term]));
  const found = {}; // term -> { dfn: [], mention: [] }
  const add = (term, kind, entry) => { (found[term] = found[term] || { dfn: [], mention: [] })[kind].push(entry); };

  for (const m of data.modules) {
    const html = fs.readFileSync(path.join(ROOT, "modules", `${m.slug}.html`), "utf8");
    const doc = new JSDOM(html).window.document;
    const main = doc.querySelector("main");
    main.querySelectorAll(".toc, [data-quiz], [data-sim]").forEach((n) => n.remove());
    const seen = new Set();
    let where = (main.querySelector("h1") || {}).textContent || m.title;
    main.querySelectorAll("h1, h2, h3, dfn[data-term]").forEach((el) => {
      if (/^H[123]$/.test(el.tagName)) { if (el.tagName !== "H1") where = el.textContent.replace(/\s+/g, " ").trim(); return; }
      const term = byLower.get(el.getAttribute("data-term").toLowerCase());
      if (!term || seen.has(term)) return;
      seen.add(term);
      add(term, "dfn", { m: m.n, kind: "dfn", id: `term-${slug(term)}`, where });
    });
    const text = main.textContent.replace(/\s+/g, " ");
    for (const g of data.glossary) {
      if (seen.has(g.term)) continue;
      if (countMentions(text, g.term) >= MIN_MENTIONS) add(g.term, "mention", { m: m.n, kind: "mention" });
    }
  }
  const index = {};
  for (const g of data.glossary) {
    const f = found[g.term];
    if (f) index[g.term] = [...f.dfn, ...f.mention];
  }
  return { index, glossary: data.glossary };
}

function render({ index, glossary }) {
  const lines = glossary.filter((g) => index[g.term]).sort((a, b) => a.term.localeCompare(b.term)).map((g) => `  ${JSON.stringify(g.term)}: ${JSON.stringify(index[g.term])}`);
  return `/* GENERATED by tools/build-glossary-index.js: do not edit by hand (run \`npm run build:glossary\`).
   term -> where it is discussed. kind "dfn": marked in the lesson (id = anchor); kind "mention": appears in the text. */
window.OSData = window.OSData || {};
window.OSData.glossaryIndex = {
${lines.join(",\n")}
};
`;
}

module.exports = { buildIndex, render, slug, OUT };

if (require.main === module) {
  const built = buildIndex(), out = render(built);
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== out) { console.error("js/data/glossary-index.js is out of date. Run: npm run build:glossary"); process.exit(1); }
    console.log("glossary index is up to date");
  } else {
    fs.writeFileSync(OUT, out);
    const total = built.glossary.length, linked = Object.keys(built.index).length;
    const firsts = Object.values(built.index).filter((v) => v[0].kind === "dfn").length;
    console.log(`Wrote ${path.relative(ROOT, OUT)}: ${linked} of ${total} terms linked (${firsts} with a marked definition, ${linked - firsts} by mention only).`);
    const missing = built.glossary.filter((g) => !built.index[g.term]).map((g) => g.term);
    if (missing.length) console.log(`Not found in any module (${missing.length}): ${missing.join(", ")}`);
  }
}
