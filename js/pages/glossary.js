(function () {
  "use strict";
  const base = document.body.dataset.root || "";
  const { h } = OSUI;
  const items = OSData.glossary.slice().sort((a, b) => a.term.localeCompare(b.term, undefined, { sensitivity: "base" }));
  const list = document.getElementById("list"), q = document.getElementById("q"), cat = document.getElementById("cat"), count = document.getElementById("count");
  const cats = ["All topics", ...[...new Set(items.map((i) => i.cat))].sort((a, b) => a.localeCompare(b))];
  cat.append(...cats.map((c) => h("option", { value: c, text: c })));

  // Where each term is discussed in the lessons (generated by tools/build-glossary-index.js)
  const where = OSData.glossaryIndex || {}, mods = Object.fromEntries(OSData.modules.map((m) => [m.n, m]));
  const modSel = document.getElementById("mod");
  modSel.append(h("option", { value: "all", text: "All lessons" }), ...OSData.modules.map((m) => h("option", { value: m.n, text: `Module ${m.n}: ${m.title}` })));
  const href = (e) => base + `modules/${mods[e.m].slug}.html${e.id ? "#" + e.id : ""}`;

  function seeAlso(term) {
    const entries = where[term];
    if (!entries?.length) return null;
    const [first, ...rest] = entries;
    const parts = [first.kind === "dfn" ? "First discussed in " : "Discussed in ", h("a", { href: href(first) }, `Module ${first.m}`),
      first.where ? ` (${first.where})` : null];
    if (rest.length) parts.push("; also in ", ...rest.flatMap((e, i) => [i ? ", " : "", h("a", { href: href(e) }, `Module ${e.m}`)]));
    return h("div", { class: "seealso" }, ...parts);
  }

  function render() {
    const needle = q.value.trim().toLowerCase(), c = cat.value, mod = modSel.value;
    const shown = items.filter((i) => (c === "All topics" || i.cat === c)
      && (mod === "all" || (where[i.term] || []).some((e) => e.m === +mod))
      && (!needle || i.term.toLowerCase().includes(needle) || i.def.toLowerCase().includes(needle)));
    list.replaceChildren();
    let letter = "", dl = null;
    shown.forEach((i) => {
      const L = i.term[0].toUpperCase();
      if (L !== letter) { letter = L; list.append(h("h2", { text: L, style: "margin-bottom:0" })); dl = h("dl", { class: "glossary" }); list.append(dl); }
      dl.append(h("dt", { id: OSSite.slug(i.term) }, i.term, h("span", { class: "cat", text: i.cat })), h("dd", {}, i.def, seeAlso(i.term)));
    });
    count.textContent = `${shown.length} of ${items.length} terms`;
    if (!shown.length) list.append(h("p", { text: "No matching terms." }));
  }
  q.addEventListener("input", render); cat.addEventListener("change", render); modSel.addEventListener("change", render);
  render();
  if (location.hash) { const t = document.getElementById(OSSite.safeDecode(location.hash.slice(1))); if (t && t.scrollIntoView) t.scrollIntoView(); }
})();
